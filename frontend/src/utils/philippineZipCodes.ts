function normalizeKey(str: string): string {
  if (!str) return '';
  return str
    .toUpperCase()
    .replace(/\s*\([^)]*\)/g, '')           // Remove parenthetical like (Capital), (Aurora)
    .replace(/^(CITY|MUNICIPALITY)\s+OF\s+/i, '')  // "CITY OF TAYABAS" -> "TAYABAS"
    .replace(/[^A-Z0-9\s-]/g, '')             // Remove special chars except hyphen
    .trim();
}

/**
 * Looks up Philippine ZIP/Postal Code given City/Municipality and optional Province.
 * Handles the exact city names from phil-reg-prov-mun-brgy including suffixes
 * like "(Capital)", prefixes like "CITY OF", and parenthetical alternates.
 */
export function getPhilippineZipCode(cityMunicipality?: string, province?: string): string {
  if (!cityMunicipality && !province) return '';

  // If only province is provided (no city selected yet), return empty
  // so we don't prematurely fill the ZIP code field
  if (!cityMunicipality && province) return '';

  const rawCity = (cityMunicipality || '').toUpperCase().trim();
  const cleanCity = normalizeKey(cityMunicipality || '');
  const rawProv = (province || '').toUpperCase().trim();
  const cleanProv = normalizeKey(province || '');

  // 1. Composite province|city exact matches (handles ambiguous city names)
  if (rawProv && cleanCity) {
    // Try with raw province
    if (PHILIPPINE_ZIP_CODES[`${rawProv}|${cleanCity}`]) {
      return PHILIPPINE_ZIP_CODES[`${rawProv}|${cleanCity}`];
    }
    // Try with clean province
    if (PHILIPPINE_ZIP_CODES[`${cleanProv}|${cleanCity}`]) {
      return PHILIPPINE_ZIP_CODES[`${cleanProv}|${cleanCity}`];
    }
    // Try cleanCity with CITY suffix
    if (PHILIPPINE_ZIP_CODES[`${cleanProv}|${cleanCity} CITY`]) {
      return PHILIPPINE_ZIP_CODES[`${cleanProv}|${cleanCity} CITY`];
    }
    // Try cleanCity without CITY suffix
    const cityWithoutSuffix = cleanCity.replace(/\s+CITY$/, '');
    if (cityWithoutSuffix !== cleanCity && PHILIPPINE_ZIP_CODES[`${cleanProv}|${cityWithoutSuffix}`]) {
      return PHILIPPINE_ZIP_CODES[`${cleanProv}|${cityWithoutSuffix}`];
    }
  }

  // 2. Direct exact match by raw city name (e.g. "LUCENA CITY")
  if (rawCity && PHILIPPINE_ZIP_CODES[rawCity]) {
    return PHILIPPINE_ZIP_CODES[rawCity];
  }

  // 3. Direct match by normalized city (e.g. "LUCENA")
  if (cleanCity && PHILIPPINE_ZIP_CODES[cleanCity]) {
    return PHILIPPINE_ZIP_CODES[cleanCity];
  }

  // 4. Try with/without CITY suffix
  if (cleanCity) {
    const withCity = cleanCity + ' CITY';
    const withoutCity = cleanCity.replace(/\s+CITY$/, '');
    if (PHILIPPINE_ZIP_CODES[withCity]) return PHILIPPINE_ZIP_CODES[withCity];
    if (withoutCity !== cleanCity && PHILIPPINE_ZIP_CODES[withoutCity]) return PHILIPPINE_ZIP_CODES[withoutCity];
  }

  // 5. Province default (only when explicitly needed, not for form auto-fill)
  if (rawProv && PROVINCE_DEFAULT_ZIP[rawProv]) {
    return PROVINCE_DEFAULT_ZIP[rawProv];
  }
  if (cleanProv && PROVINCE_DEFAULT_ZIP[cleanProv]) {
    return PROVINCE_DEFAULT_ZIP[cleanProv];
  }

  // 6. Substring/partial match as last resort
  if (cleanCity) {
    for (const [key, val] of Object.entries(PHILIPPINE_ZIP_CODES)) {
      const cityPart = key.includes('|') ? key.split('|')[1] : key;
      if (cleanCity.length >= 4 && cityPart.includes(cleanCity)) {
        return val;
      }
    }
  }

  return '';
}
